function _b64ToBytes(b64) {
  const bin = atob(b64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return bytes.buffer;
}

async function ensureFeedalotTemplate(group) {
  const held = await DB.getMaster(group);
  if (held) return;
  try {
    await DB.putMaster(group, _b64ToBytes(FA_EMBEDDED_TEMPLATE_B64));
  } catch (e) {
    console.warn("FeedAlot template install failed for", group, e);
  }
}
